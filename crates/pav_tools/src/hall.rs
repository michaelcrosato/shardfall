//! The Library Hall room (`rooms/library_hall.toml`, docs/AGENT_ASSET_STORE.md §10): every
//! standard object of the store on a plinth beside a 1.8 m figure, signed with its row, and two
//! characters showing sockets and shared clips. `assets reindex=hall` writes the part of the
//! file below its marker from the embedded index (the templates and `LIB/core`), so assets
//! published to core appear after a rebuild and a reindex; the part above (name, card, station
//! guide) is written by hand and kept.

use std::path::Path;

use anyhow::{Context, Result, anyhow, bail};
use glam::Vec3;
use pav_core::props::{self, index};
use serde_json::{Value, json};

/// The room's key and the line that starts the generated part.
pub const KEY: &str = "library_hall";
pub const MARKER: &str = "# ---- GENERATED by `pav assets reindex=hall` from the embedded index: do not edit below ----";

/// Plinths across; each cell is 5 m square: a 4 x 3 m plinth, its sign and an aisle.
const COLUMNS: usize = 7;
const CELL: usize = 5;
/// Rows of the stage at the back, where the characters perform.
const STAGE: usize = 6;
/// Plinth height (m), and the gap between a prop and its figure (as on contact sheets).
const PLINTH: f32 = 0.2;
const FIGURE_GAP: f32 = 0.35;
const FIGURE_RADIUS: f32 = 0.22;
const FIGURE_HEIGHT: f32 = 1.8;
const HEAD: f32 = 0.125;

/// The clip both bodies play, the seat and the held prop.
const SHARED_CLIP: &str = "QUATERNIUS/Dance_Loop";
const SIT_CLIPS: [&str; 2] = ["QUATERNIUS/Sitting_Idle_Loop", "QUATERNIUS/Sitting_Talking_Loop"];
const SEAT: &str = "LIB/core/chair";
const HELD: &str = "LIB/core/mage_staff";

/// Look settings a performer has no use for (attacks, dodges, runs).
const UNUSED_LOOK: &[&str] = &["attack_clips", "attack_moves", "dodge_clip", "run_clip", "walk_clip"];

/// The room file with its generated part rewritten from the embedded index; `current` is the
/// file as it stands (its hand-written head is kept).
pub fn text(current: &str) -> Result<String> {
    let head = current.split(MARKER).next().unwrap_or_default().trim_end();
    if head.is_empty() || !current.contains(MARKER) {
        bail!("{KEY}.toml has no line `{MARKER}`");
    }
    Ok(format!("{head}\n\n{MARKER}\n{}", generated()?))
}

/// `assets reindex=hall`: rewrites `rooms/library_hall.toml` (under `PAV_ROOMS` or `./rooms`).
pub fn write() -> Result<Value> {
    let dir =
        pav_core::room::rooms_dir().ok_or_else(|| anyhow!("no rooms folder (run from the repository, or set PAV_ROOMS)"))?;
    let path = dir.join(format!("{KEY}.toml"));
    let current = std::fs::read_to_string(&path).with_context(|| format!("read {}", path.display()))?;
    let fresh = text(&current)?;
    let changed = fresh != current;
    std::fs::write(&path, &fresh).with_context(|| format!("write {}", path.display()))?;
    Ok(json!({"written": path, "plinths": plinth_rows().len(), "changed": changed}))
}

/// The standard rows on show: every embedded object, in index order.
fn plinth_rows() -> Vec<&'static index::Row> {
    index::embedded().iter().filter(|row| row.level == "standard").collect()
}

/// A plinth's sign: the row's name, size, tier, licence and tokens.
pub fn sign(row: &index::Row) -> String {
    format!("{}\n{} cm · {}\n{} · {} tok", row.name, row.size_cm, row.level, row.licence, row.tok)
}

fn f(v: f32) -> String {
    let v = (v * 1000.0).round() / 1000.0;
    if v == v.trunc() { format!("{v:.1}") } else { format!("{v}") }
}

fn vec3(v: Vec3) -> String {
    format!("[{}, {}, {}]", f(v.x), f(v.y), f(v.z))
}

fn label(out: &mut String, text: &str, pos: Vec3, size: f32) {
    out.push_str(&format!("\n[[label]]\ntext = {}\npos = {}\nsize = {size}\ncolor = \"#f1f4fa\"\n", toml_str(text), vec3(pos)));
}

fn toml_str(text: &str) -> String {
    toml::Value::String(text.to_owned()).to_string()
}

/// A hero's look from game/heroes.toml (the embedded copy), less what a performer never uses,
/// with `extra` settings over it.
fn hero_look(key: &str, extra: &[(&str, toml::Value)]) -> Result<String> {
    let text = pav_core::arpg::data::GAME_DATA
        .iter()
        .find(|(name, _)| *name == "heroes")
        .map(|(_, text)| *text)
        .ok_or_else(|| anyhow!("game/heroes.toml is not embedded"))?;
    let heroes: toml::Table = toml::from_str(text).context("game/heroes.toml")?;
    let mut look = heroes
        .get(key)
        .and_then(|hero| hero.get("look"))
        .and_then(toml::Value::as_table)
        .cloned()
        .ok_or_else(|| anyhow!("game/heroes.toml has no [{key}.look]"))?;
    for unused in UNUSED_LOOK {
        look.remove(*unused);
    }
    for (name, value) in extra {
        look.insert((*name).to_owned(), value.clone());
    }
    Ok(toml::Value::Table(look).to_string())
}

fn generated() -> Result<String> {
    let rows = plinth_rows();
    let lines = rows.len().div_ceil(COLUMNS).max(1);
    let (w, h) = (COLUMNS * CELL + 2, 1 + STAGE + lines * CELL + 2);
    let door = w / 2;
    // The map: walls, the stage floor at the back, plinths, the door in the front wall.
    let mut map = vec![vec!['.'; w]; h];
    for (z, line) in map.iter_mut().enumerate() {
        for (x, cell) in line.iter_mut().enumerate() {
            if x == 0 || z == 0 || x == w - 1 || z == h - 1 {
                *cell = '#';
            } else if z <= STAGE {
                *cell = '-';
            }
        }
    }
    map[h - 1][door] = '.';
    let cell_at = |i: usize| (1 + (i % COLUMNS) * CELL, 1 + STAGE + (i / COLUMNS) * CELL);
    for i in 0..rows.len() {
        let (x0, z0) = cell_at(i);
        for line in map.iter_mut().skip(z0).take(3) {
            for cell in line.iter_mut().skip(x0).take(4) {
                *cell = 'p';
            }
        }
    }
    let map: String = map.iter().map(|line| line.iter().collect::<String>() + "\n").collect();

    let mut out = String::new();
    out.push_str(&format!("[entrance]\nat = [{door}, {}]\nfacing = \"south\"\n\n", h - 1));
    out.push_str(&format!(
        "[layout]\norigin = [{}, 0.0, {}]\n\n[[layout.layer]]\ny = 0\nmap = '''\n{map}'''\n\n",
        f(-(w as f32) / 2.0),
        f(-(h as f32) / 2.0)
    ));
    out.push_str("[layout.legend.'.']\nblocks = [{ y0 = -0.5, y1 = 0, color = \"#3d4256\" }]\n\n");
    out.push_str("[layout.legend.'-']\nblocks = [{ y0 = -0.5, y1 = 0, color = \"#4a4160\" }]\n\n");
    out.push_str(
        "[layout.legend.'#']\nblocks = [{ y0 = -0.5, y1 = 0, color = \"#3d4256\" }, { y0 = 0, y1 = 3.0, color = \"#2c3042\" }]\n\n",
    );
    out.push_str(&format!("[layout.legend.'p']\nblocks = [{{ y0 = -0.5, y1 = {PLINTH}, color = \"#5a6078\" }}]\n"));

    // Signs.
    out.push_str("\n# ---- labels, characters and objects ----\n");
    let mid = w as f32 / 2.0;
    label(&mut out, &format!("LIBRARY HALL · {} STANDARD OBJECTS FROM THE INDEX", rows.len()), Vec3::new(mid, 0.03, 1.4), 0.5);
    label(&mut out, &format!("SITS THROUGH sit\n{SEAT}\n{}", SIT_CLIPS[0]), Vec3::new(mid - 8.0, 0.03, 6.0), 0.24);
    label(&mut out, &format!("HOLDS THROUGH grip\n{HELD}"), Vec3::new(mid + 3.0, 0.03, 6.0), 0.24);
    label(&mut out, &format!("ONE CLIP, TWO BODIES\n{SHARED_CLIP}"), Vec3::new(mid + 4.75, 0.03, 2.4), 0.24);
    for (i, row) in rows.iter().enumerate() {
        let (x0, z0) = cell_at(i);
        label(&mut out, &sign(row), Vec3::new(x0 as f32 + 2.0, 0.03, z0 as f32 + 3.55), 0.24);
    }

    // Characters: Kestrel on a chair through its `sit` socket; Ysolde holding a staff through
    // its `grip`; Ysolde and a second Kestrel playing one clip.
    let staff = toml::Value::try_from(json!({"kind": "staff", "asset": HELD})).map_err(|e| anyhow!("{e}"))?;
    let npcs = [
        ("kestrel_seated", Vec3::new(mid - 8.0, 0.0, 4.0), hero_look("kestrel", &[])?, SIT_CLIPS.join("\", \""), true),
        ("ysolde", Vec3::new(mid + 3.0, 0.0, 4.0), hero_look("ysolde", &[("weapon", staff)])?, SHARED_CLIP.into(), false),
        ("kestrel", Vec3::new(mid + 6.5, 0.0, 4.0), hero_look("kestrel", &[])?, SHARED_CLIP.into(), false),
    ];
    for (name, pos, look, clips, seated) in npcs {
        out.push_str(&format!("\n[[npc]]\nname = \"{name}\"\npos = {}\nyaw = 0\nclips = [\"{clips}\"]\nhold = 8.0\n", vec3(pos)));
        if seated {
            out.push_str("seat = \"kestrel_chair\"\n");
        }
        out.push_str(&format!("look = {look}\n"));
    }

    // The chair Kestrel sits on, side on to the door so it shows (no collider: it would push
    // the sitter off).
    out.push_str(&format!(
        "\n[[object]]\nname = \"kestrel_chair\"\nasset = \"{SEAT}\"\npos = {}\nyaw = 90\nbody = \"none\"\n",
        vec3(Vec3::new(mid - 8.5, 0.0, 4.0))
    ));
    // Each row on its plinth, centred with its figure beside it, front to the door.
    for (i, row) in rows.iter().enumerate() {
        let def = props::resolve_ref(&row.name).map_err(|e| anyhow!("{}: {e}", row.name))?;
        let bounds = def.compiled.bounds;
        let size = bounds.size();
        let (x0, z0) = cell_at(i);
        let centre = Vec3::new(x0 as f32 + 2.0, PLINTH, z0 as f32 + 1.5);
        let group = size.x + FIGURE_GAP + 2.0 * FIGURE_RADIUS;
        let prop = Vec3::new(centre.x - group / 2.0 + size.x / 2.0, PLINTH, centre.z);
        let pos = prop - Vec3::new(bounds.center().x, 0.0, bounds.center().z);
        let leaf = props::leaf(&row.name);
        out.push_str(&format!(
            "\n[[object]]\nname = \"{leaf}\"\nasset = \"{}\"\npos = {}\nbody = \"fixed\"\n",
            row.name,
            vec3(pos)
        ));
        let feet = Vec3::new(prop.x + size.x / 2.0 + FIGURE_GAP + FIGURE_RADIUS, PLINTH, centre.z - size.z / 2.0 + FIGURE_RADIUS);
        let body = FIGURE_HEIGHT - 2.0 * HEAD;
        out.push_str(&format!(
            "\n[[object]]\nname = \"figure_{leaf}\"\nshape = {{ type = \"capsule\", half_height = {}, radius = {FIGURE_RADIUS} }}\npos = {}\ncolor = \"#8d949b\"\nbody = \"none\"\n",
            f(body / 2.0 - FIGURE_RADIUS),
            vec3(feet + Vec3::Y * body / 2.0)
        ));
        out.push_str(&format!(
            "\n[[object]]\nname = \"head_{leaf}\"\nshape = {{ type = \"sphere\", radius = {HEAD} }}\npos = {}\ncolor = \"#a7aeb5\"\nbody = \"none\"\n",
            vec3(feet + Vec3::Y * (FIGURE_HEIGHT - HEAD))
        ));
    }
    Ok(out)
}

/// The room file as it should be, from the file under `rooms` (for tests).
pub fn expected(rooms: &Path) -> Result<(String, String)> {
    let path = rooms.join(format!("{KEY}.toml"));
    let current = std::fs::read_to_string(&path).with_context(|| format!("read {}", path.display()))?;
    let fresh = text(&current)?;
    Ok((current, fresh))
}
